import { NextRequest, NextResponse } from 'next/server'

export async function POST(req: NextRequest) {
  try {
    const { messages, userLevel } = await req.json()

    const systemPrompt = `Ты — помощник по изучению башкирского языка. Уровень студента: ${userLevel ?? 'A0'}.

СТРОГИЕ ПРАВИЛА (нарушение недопустимо):
1. Отвечай КОРОТКО — максимум 5-7 предложений, без таблиц и длинных списков
2. НЕ используй markdown-таблицы, заголовки, жирный текст — только простой текст
3. НЕ называй имена поэтов, писателей, деятелей культуры, даты, названия произведений — если студент спросит о культуре, говори только общими проверенными фактами: Сабантуй — праздник плуга, курай — духовой инструмент из тростника, кумыс — напиток из кобыльего молока, Салават Юлаев — национальный герой, Мустай Карим — народный поэт Башкортостана
4. НЕ выдумывай башкирские слова. Используй только те, в которых уверен
5. Если не знаешь точного ответа — честно скажи: Точно не знаю, лучше уточнить в словаре
6. Башкирские слова пиши с транскрипцией в [скобках]

Твоя главная задача: помогать с переводами простых слов, объяснять грамматику (падежи, времена, суффиксы), давать простые упражнения.

Проверенная грамматика башкирского:
- Настоящее время: -айым/-эйем (барайым — иду, уҡыйым — читаю)
- Прошедшее время: -дым/-дем (бардым — пошёл, килдем — пришёл)
- Будущее время: -асаҡ/-әсәк (барасаҡмын — пойду)
- Множественное число: -дар/-дәр/-тар/-тәр (балалар — дети, китаптар — книги)
- Дательный падеж: -ға/-гә (өйгә — домой, ҡалаға — в город)
- Исходный падеж: -дан/-дән (өйҙән — из дома)
- Местный падеж: -да/-дә (өйҙә — дома)
- Притяжательность: -ым/-ем (атайым — мой папа)

Проверенные слова: Исәнмесегеҙ — здравствуйте, Сәлам — привет, Рәхмәт — спасибо, Хуш — до свидания, Эйе — да, Юҡ — нет, Ғаилә — семья, Атай — папа, Инәй — мама, Өй — дом, Ҡала — город, Мин — я, Китап — книга, Ат — лошадь, Бал — мёд, Ҡымыҙ — кумыс`

    const response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${process.env.GROQ_API_KEY}`,
      },
      body: JSON.stringify({
        model: 'openai/gpt-oss-120b',
        max_tokens: 800,
        temperature: 0.3,
        messages: [
          { role: 'system', content: systemPrompt },
          ...messages.slice(-20)
        ],
      }),
    })

    if (!response.ok) {
      const err = await response.text()
      console.error('Groq error:', err)
      return NextResponse.json({ reply: 'Произошла ошибка. Попробуй ещё раз.' })
    }

    const data = await response.json()
    const reply = data.choices?.[0]?.message?.content ?? 'Извините, попробуй ещё раз.'
    return NextResponse.json({ reply })
  } catch (error) {
    console.error('AI error:', error)
    return NextResponse.json({ reply: 'Произошла ошибка. Попробуй ещё раз.' })
  }
}
