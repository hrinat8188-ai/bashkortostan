export async function POST(req: NextRequest) {
  try {
    const { lessonTitle, level, count } = await req.json()

    const msg = `Ты преподаватель башкирского языка. Используй ТОЛЬКО слова из словаря ниже.

${BASHKIR_KNOWLEDGE}

Создай ${count} РАЗНЫХ упражнений строго по теме "${lessonTitle}" для уровня ${level}.
Каждое упражнение должно быть УНИКАЛЬНЫМ — не повторяй вопросы.
Используй разные форматы: перевод с башкирского, перевод на башкирский, грамматика, примеры предложений.

Верни ТОЛЬКО JSON массив:
[{"question":"вопрос","answers":[{"text":"правильный","is_correct":true},{"text":"неверно1","is_correct":false},{"text":"неверно2","is_correct":false},{"text":"неверно3","is_correct":false}],"explanation":"объяснение с транскрипцией"}]`

    const response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${process.env.GROQ_API_KEY}`,
      },
      body: JSON.stringify({
        model: 'openai/gpt-oss-120b',
        max_tokens: 4000,
        temperature: 0.8,
        messages: [{ role: 'user', content: msg }],
      }),
    })

    if (!response.ok) {
      const err = await response.text()
      console.error('Groq error:', err)
      return NextResponse.json({ exercises: [] }, { status: 500 })
    }

    const data = await response.json()
    const text = data.choices?.[0]?.message?.content ?? ''
    const jsonMatch = text.match(/\[[\s\S]*\]/)
    if (!jsonMatch) {
      return NextResponse.json({ exercises: [] }, { status: 500 })
    }

    const exercises = JSON.parse(jsonMatch[0])
    return NextResponse.json({ exercises })
  } catch (error) {
    console.error('Generate error:', error)
    return NextResponse.json({ exercises: [] }, { status: 500 })
  }
}
